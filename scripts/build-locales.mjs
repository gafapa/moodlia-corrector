import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const locales = ['en', 'es', 'fr', 'de', 'pt_BR', 'it', 'gl', 'ca'];
const rows = (await readFile('scripts/localization/messages.txt', 'utf8')).split(/\r?\n/).filter(line => line && !line.startsWith('#')).map(line => {
  const values = line.split('|');
  if (values.length !== locales.length || values.some(value => !value.trim())) throw new Error(`Invalid translation row: ${line}`);
  const expected = [...values[0].matchAll(/\$\d+/g)].map(match => match[0]).sort().join(',');
  for (const value of values) if ([...value.matchAll(/\$\d+/g)].map(match => match[0]).sort().join(',') !== expected) throw new Error(`Translation placeholders differ: ${values[0]}`);
  return values;
});
const catalogs = Object.fromEntries(locales.map(locale => [locale, {}]));
const aliases = {};
for (const values of rows) {
  const key = `m${createHash('sha256').update(values[0]).digest('hex').slice(0, 12)}`;
  for (const source of values.slice(0, 2)) aliases[source] = key;
  locales.forEach((locale, index) => { catalogs[locale][key] ||= { message: values[index], description: values[0] }; });
}
const descriptions = ['Teacher-reviewed AI feedback for Moodle assignments.', 'Comentarios de IA para tareas Moodle, revisados por el docente.', 'Commentaires IA pour les devoirs Moodle, vérifiés par l’enseignant.', 'KI-Feedback für Moodle-Aufgaben, von der Lehrkraft geprüft.', 'Comentários de IA para tarefas Moodle, revisados pelo professor.', 'Feedback IA per compiti Moodle, verificato dal docente.', 'Comentarios de IA para tarefas Moodle, revisados polo docente.', 'Comentaris d’IA per a tasques Moodle, revisats pel docent.'];
for (const [index, locale] of locales.entries()) {
  catalogs[locale].extensionName = { message: 'MoodlIA Corrector' };
  catalogs[locale].extensionDescription = { message: descriptions[index] };
  await mkdir(`extension/_locales/${locale}`, { recursive: true });
  const nativeCatalog = Object.fromEntries(Object.entries(catalogs[locale]).map(([key, entry]) => {
    const numbers = [...new Set([...entry.message.matchAll(/\$(\d+)/g)].map(match => match[1]))];
    return [key, numbers.length ? { ...entry,
      message: entry.message.replace(/\$(\d+)/g, (_, number) => `$value${number}$`),
      placeholders: Object.fromEntries(numbers.map(number => [`value${number}`, { content: `$${number}`, example: `Example ${number}` }])),
    } : entry];
  }));
  await writeFile(`extension/_locales/${locale}/messages.json`, `${JSON.stringify(nativeCatalog, null, 2)}\n`);
}
await writeFile('extension/src/i18nMessages.js', `// Generated by scripts/build-locales.mjs. Edit scripts/localization/messages.txt.\nglobalThis.MoodliaCorrectorMessages = ${JSON.stringify({ locales, aliases, catalogs })};\n`);
console.log(`Built ${Object.keys(catalogs.en).length} messages for ${locales.length} locales.`);
